const W = 5, H = 7, GAP = 1;
const glyph = c => G[c] || G[c.toLowerCase()] || G['?'];
/* width in pixels of `text` at `scale`, with one blank column between glyphs */
const measure = (text, scale) => text.length ? (text.length * (W + GAP) - GAP) * scale : 0;
/* calls dot(x, y, size) for every lit pixel */
function draw(text, x, y, scale, dot) {
  [...text].forEach((c, i) => {
    const g = glyph(c), ox = x + i * (W + GAP) * scale;
    for (let r = 0; r < g.length; r++) for (let k = 0; k < W; k++) if (g[r][k] === '#') dot(ox + k * scale, y + r * scale, scale);
  });
}
module.exports = { W, H, GAP, measure, draw, has: c => !!G[c.toLowerCase()] };
